// регион телефонного номера контрагента
//
// это НЕ страна регистрации аккаунта: номер может быть любой. Показываем
// отдельно и подписываем как регион номера, чтобы одно не выдавали за другое.
//
// биржа отдаёт номер замаскированным (+7••••••8169), поэтому смотрим только на
// цифры ДО маски: хвост — это последние знаки номера, и если приклеить его к
// префиксу, «+7••••••7712» превратится в 77712 и совпадёт с кодом Казахстана

// длинные коды раньше коротких, иначе +7 съест +77
const REGIONS: [string, string][] = [
  ['998', 'Узбекистан'],
  ['996', 'Киргизия'],
  ['995', 'Грузия'],
  ['994', 'Азербайджан'],
  ['993', 'Туркмения'],
  ['992', 'Таджикистан'],
  ['971', 'ОАЭ'],
  ['380', 'Украина'],
  ['375', 'Беларусь'],
  ['374', 'Армения'],
  ['373', 'Молдавия'],
  ['90', 'Турция'],
  ['77', 'Казахстан'],
  ['76', 'Казахстан'],
  ['79', 'Россия'],
  ['78', 'Россия'],
  ['74', 'Россия'],
  ['73', 'Россия'],
  // код страны у России и Казахстана общий: без второй цифры не различить
  ['7', 'Россия или Казахстан'],
];

/**
 * Ведущие цифры номера — всё до первого символа маски.
 * `+7••••••8169` → `7`, `+7701••1234` → `7701`, `••••8169` → пусто.
 */
function leadingDigits(masked: string): string {
  const trimmed = masked.trim().replace(/^\+/, '');
  return /^\d+/.exec(trimmed)?.[0] ?? '';
}

export function phoneRegion(masked: string | null | undefined): string | null {
  if (!masked) return null;

  const digits = leadingDigits(masked);
  if (!digits) return null;

  for (const [prefix, region] of REGIONS) {
    if (digits.startsWith(prefix)) return region;
  }
  return null;
}
